  function normalizeLanguage(value) {
    const code = String(value || "").trim().toLowerCase().split("-")[0];
    return SUPPORTED.includes(code) ? code : "en";
  }

  function storedLanguage() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored) return normalizeLanguage(stored);
    } catch {
    }
    return normalizeLanguage(
      typeof navigator === "object" ? navigator.language : "en"
    );
  }

  let currentLanguage = storedLanguage();

  function t(key, values = {}) {
    const template = messages[currentLanguage]?.[key] ??
      messages.en[key] ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) =>
      Object.hasOwn(values, name) ? String(values[name]) : match
    );
  }

  function formatNumber(value, digits = 1) {
    const locales = { en: "en-GB", fr: "fr-FR", ar: "ar-TN" };
    return new Intl.NumberFormat(locales[currentLanguage], {
      maximumFractionDigits: digits
    }).format(value);
  }

  function monthShort(month) {
    const locales = { en: "en-GB", fr: "fr-FR", ar: "ar-TN" };
    return new Intl.DateTimeFormat(locales[currentLanguage], {
      month: "short"
    }).format(new Date(2024, Number(month) - 1, 1));
  }

  function apply(rootNode) {
    if (typeof document === "undefined") return;
    document.documentElement.lang = currentLanguage;
    document.documentElement.dir = RTL.has(currentLanguage) ? "rtl" : "ltr";
    const root = rootNode || document;
    root.querySelectorAll("[data-i18n]").forEach(node => {
      node.textContent = t(node.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(node => {
      node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
    });
    root.querySelectorAll("[data-i18n-label]").forEach(node => {
      node.setAttribute("label", t(node.dataset.i18nLabel));
    });
    root.querySelectorAll("[data-i18n-aria-label]").forEach(node => {
      node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
    });
    root.querySelectorAll("[data-language-select]").forEach(select => {
      select.value = currentLanguage;
      if (select.dataset.i18nBound !== "true") {
        select.dataset.i18nBound = "true";
        select.addEventListener("change", event => {
          setLanguage(event.target.value);
        });
      }
    });
  }

  function setLanguage(value) {
    const next = normalizeLanguage(value);
    if (next === currentLanguage) {
      apply(document);
      return;
    }
    currentLanguage = next;
    try {
      localStorage.setItem(STORAGE_KEY, currentLanguage);
    } catch {
    }
    apply(document);
    window.dispatchEvent(new CustomEvent("solarna:languagechange", {
      detail: { language: currentLanguage }
    }));
  }

  if (typeof document !== "undefined") {
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", () => apply(document), {
        once: true
      });
    } else {
      apply(document);
    }
  }

  return Object.freeze({
    apply,
    formatNumber,
    get language() {
      return currentLanguage;
    },
    messages,
    monthShort,
    setLanguage,
    supported: SUPPORTED,
    t
  });
